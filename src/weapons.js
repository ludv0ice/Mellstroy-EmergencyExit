const sharpWeapons = ['Knife', 'Sword', 'Axe', 'Machete', 'Drill'];
const silentGuns = ['Silencer', 'SilencedUzi'];

export const WEAPONS = definitions.map((definition, id) => {
  const { sprite, ammo = 0 } = definition;
  const gun = ammo > 0;
  const reach = melee[sprite]?.reach ?? 0;
  return {
    id,
    name: definition.name,
    sprite,
    ammo,
    gun,
    cooldown: gun ? definition.cooldown : melee[sprite].cooldown,
    pellets: definition.pellets ?? 0,
    spread: definition.spread ?? 0,
    speed: gun ? 960 : 0,
    sound: definition.sound ?? 'sndSwing1',
    range: Math.round(reach * 1.2),
    enemyRange: Math.round(reach * 0.7),
    sharp: sharpWeapons.includes(sprite),
    throwOnly: sprite === 'Throw',
    silent: silentGuns.includes(sprite),
  };
});

export const UNARMED = {
  id: -1,
  name: 'Кулаки',
  sprite: 'Unarmed',
  gun: false,
  ammo: 0,
  cooldown: 20 / 60,
  range: 25,
  sound: 'sndPunch',
};

export function weaponBySprite(name = '') {
  const sprite = name.replace(/^(sprPolice|sprE|sprP)(Walk|Attack)/, '');
  return WEAPONS.find((weapon) => weapon.sprite === sprite) ?? UNARMED;
}
